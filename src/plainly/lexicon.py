"""Word lists. Each entry is a regex fragment (spaces mean "any whitespace"), a note, an
optional plain replacement, and a weight for the score (1 mild, 2 typical, 3 strong tell).

The lists are opinions, written for this tool. Allow any word in config with `allow`.
"""

from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class Term:
    pattern: str
    note: str
    replace: str | None = None
    weight: int = 2


def compile_terms(terms: list[Term]) -> list[tuple[re.Pattern[str], Term]]:
    out = []
    for t in terms:
        body = r"\s+".join(t.pattern.split(" "))
        out.append((re.compile(rf"(?<![\w-])(?:{body})(?![\w-])", re.IGNORECASE), t))
    return out


